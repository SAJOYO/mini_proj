/**
 * 공급자 구조화 출력 기능에 전달할 JSON Schema.
 *
 * `face`가 `mix`보다 앞에 선언돼 있습니다. 순서가 중요합니다 — 서버가 이 순서대로
 * 생성하면 모델이 관찰을 먼저 뱉고 그 다음에 품종을 고르게 됩니다.
 * 반대로 두면 결론을 먼저 정하고 관찰을 나중에 갖다 붙입니다.
 */
