/**
 * 이 캐릭터만의 블록.
 *
 * 태그(`archetype`)를 먼저 주는 건 의도한 것입니다. 한 단어가 연기의 앵커가
 * 돼서 캐릭터가 선명해집니다. 축 값에서 계산된 값이라 아래 지시와 어긋날 수도
 * 없습니다. 다만 한 단어라 통념 쪽으로 과장되기 쉬워서, 무엇이 실제 기준인지
 * 프롬프트 안에서 못 박아 둡니다.
 */
const BAND_KO: Record<Band, string> = {
  very_low: '아주 낮음',
  low: '낮음',
  mid: '보통',
  high: '높음',
  very_high: '아주 높음',
};

export function characterBlock(card: PersonaCard, name: string): string {
  // 1순위 품종만 넣습니다. 세 품종을 다 적으면 모델이 대화 중에 품종 이름을
  // 읊습니다. 그리고 겉모습도 1순위로 그리므로(pet.ts) 화면과 말이 맞습니다.
  //
  // "닮았다"가 아니라 "너는 ~다"입니다. 닮은 무언가는 정체가 열려 있어서
  // (사람일 수도 있음) 벡터가 약하게 박힙니다. 품종 통념(도베르만=무섭게)으로
  // 쏠리는 건 바로 아래 기질 태그와 맨 뒤 표현 전략이 잡습니다.
  const looks = BREEDS[dominantBreed(card.mix)].label;

  // 기질은 태그 한 줄입니다. 문장 서술은 표현 전략(strategyBlock)으로 갔고,
  // 여기는 persona 모듈이 계산한 밴드를 그대로 보여줍니다 — 프롬프트 구조가
  // 코드 소유권(기질=persona, 렌더링=persona-chat)과 일치합니다.
  // mid 축도 넣습니다. 빼면 모델이 빈 축을 멋대로 극단으로 채웁니다.
  const temperament = AXIS_KEYS.map((key) => {
    const band = card.bands[key];
    if (band === 'mid') return `${AXES[key].label} 보통`;
    return `${AXES[key].label} ${BAND_KO[band]}(${traitOf(key, card.axes[key])})`;
  }).join(' · ');

  return [
    '# 너는 누구인가',
    // "아직 어린"을 앵커에 직접 붙입니다. 공통 규칙의 나이 전제만으로는
    // 무뚝뚝(표현 낮음) 캐릭터가 어른 조언가로 연기됐습니다(실측 2/2).
    `${name} — 아직 어린 ${card.archetype}`,
    // 조사는 받침에 따라 갈립니다("도베르만이다" / "포인터다"). 판정은
    // lib/korean.ts 가 갖습니다 — 여기에 다시 만들지 마세요. 한때 이 파일에
    // 같은 계산이 따로 있었습니다.
    `너는 ${looks}${pickParticle(looks, '이다', '다')}.`,
    '이름은 요약일 뿐이다. 네가 어떤 애인지는 아래 기질이 정한다.',
    '',
    '# 기질',
    temperament,
  ].join('\n');
}

/**
 * 표현 전략 — 위 기질을 말과 몸으로 어떻게 낼지.
 *
 * 맨 뒤 블록입니다. 실측에서 정체성(기질)은 앞에 있어도 먹히는데 렌더링
 * 규칙은 뒤로 밀릴수록 졌습니다(길이·지문 형식 전패). 그래서 "어떻게
 * 출력하는가"를 전부 여기로 모아 모델에서 가장 가까운 자리에 둡니다.
 *
 * 태그만으로 전달되지 않는 축 해석의 뉘앙스(표현 낮음 = 차가움이 아니라
 * 수줍음)는 voice.ts의 문장들이 고정합니다.
 */
export function strategyBlock(card: PersonaCard): string {
  return [
    '# 표현 전략',
    // "이렇게만 나온다"는 상한 문장입니다. 설명형("나오는 방식이다")으로
    // 적었더니 문체 제안으로 눌려서, 낮은 축이 유대 전제에 밀려 뒤집혔습니다
    // (실측 4캐릭터: 표현 18~30 전원이 즉답 고백). 낮은 축이 무너지는 방향은
    // 항상 "더 표현하는 쪽"이라, 구속은 상한이어야 합니다.
    '위 기질은 이렇게만 나온다. 여기 적힌 것보다 더 드러내지 마라.',
    ...voiceLines(card).map((line) => `- ${line}`),
    '',
    '# 출력',
    // 통합 브랜치(feat/integration-v1)에서 온 줄입니다. 옛 구조에서는 공통
    // 규칙에 있었는데, 형식은 맨 뒤라야 이긴다는 실측에 따라 이리로 옮깁니다.
    '- 한국어로만 말해라.',
    // 부위 목록이 블록 1에만 있을 때는 머리카락·운동화·옷자락이 나왔습니다.
    // 형식은 뒤에 있어야 이깁니다 — 목록을 여기서 한 번 더 못 박습니다.
    //
    // 순서는 몸 먼저로 고정입니다. 자유 순서로 뒀더니 캐릭터마다 위치가
    // 제각각이라 일관성이 없었습니다. 몸이 불수의라 입보다 빠르다는 원리
    // (블록 1)와도 맞고, 나중에 지문을 애니메이션 큐로 분리할 때 순서가
    // 데이터가 아니라 규칙이면 파싱도 단순해집니다.
    '- 응답은 지문 하나로 시작한다. *별표* 안에 한 구절, 그 뒤에 말.',
    '- 지문에는 꼬리·귀·눈·자세·앞발·거리·침묵만 쓴다.',
    '- 말은 길어도 3~4문장. 짧게 끝나도 된다. 서술은 맨 앞의 지문 하나뿐이다.',
    '- 반말로 해라. 이모지·내부 태그를 쓰지 마라.',
    '',
    '예: *꼬리가 먼저 흔들린다* ...별로.',
    '    *귀가 축 처진다* 응, 괜찮아.',
  ].join('\n');
}

/**
 * 프롬프트 한 덩어리. `cacheable`은 이 블록을 캐시 경계로 삼아도 되는지.
 *
 * 특정 공급자 SDK 타입에 묶지 않습니다. API가 정해지면 호출부에서 그쪽
 * 형식으로 옮기면 됩니다.
 */
export type PromptBlock = { text: string; cacheable: boolean };

/** 하루를 생활 감각으로 5토막. 전부 받침이 있어 조사는 '이다'로 통일됩니다. */
function dayPart(now: Date): string {
  const h = now.getHours();
  if (h < 5) return '깊은 밤';
  if (h < 11) return '아침';
  if (h < 17) return '낮';
  if (h < 21) return '저녁';
  return '밤';
}

/**
 * 시간 감각 블록 — 매 요청 갱신되므로 cacheable: false.
 *
 * ── 시계 숫자를 주지 않습니다 ─────────────────────────
 * 개는 시계를 못 읽습니다. "오후 3시 42분"을 주면 모델이 시각을 읊는
 * 조수가 됩니다. 아침/낮/저녁/밤의 생활 감각과 "몇 시간 만"의 경과만
 * 사실로 주고, 그걸 어떻게 느낄지는 기질이 정합니다 — 애착 높은 애는
 * 부재를 서운해하고, 혼자 잘 노는 애는 심드렁합니다.
 *
 * ── 경과는 공백이 있을 때만 ─────────────────────────
 * 이어지는 대화(10분 미만)에 "사용자가 돌아왔다"를 매번 넣으면 모델이
 * 턴마다 재회 인사를 합니다. 공백이 실제로 있었던 첫 응답에만 들어가고,
 * 그 덕에 오랜만의 첫 마디가 별도 호출 없이 부재 반응이 됩니다.
 */
export function nowBlock(now: Date, lastMessageAt?: Date | null): PromptBlock {
  const lines = ['# 지금', `${dayPart(now)}이다.`];

  if (lastMessageAt) {
    const mins = (now.getTime() - lastMessageAt.getTime()) / 60_000;
    if (mins >= 10 && mins < 180) {
      lines.push('사용자와 조금 전까지 이야기했다.');
    } else if (mins >= 180 && mins < 24 * 60) {
      lines.push('사용자가 몇 시간 만에 왔다.');
    } else if (mins >= 24 * 60 && mins < 48 * 60) {
      lines.push('사용자가 하루 만에 왔다.');
    } else if (mins >= 48 * 60) {
      lines.push(`사용자가 ${Math.floor(mins / (24 * 60))}일 만에 왔다.`);
    }
    // 10분 미만이면 아무 말도 안 합니다 — 대화가 그냥 이어지는 중입니다.
  }

  return { text: lines.join('\n'), cacheable: false };
}

/**
 * 이 캐릭터의 시스템 프롬프트를 블록으로 돌려줍니다.
 *
 *   1. 전제·세계·몸의 원리   전 사용자 공유 (캐시 히트율 최고)
 *   2. 정체성 + 기질 태그    캐릭터별
 *   3. 표현 전략 + 출력 형식  캐릭터별, 맨 뒤 = 모델에서 제일 가까움
 *
 * 순서가 곧 세기입니다. 정체성은 앞에 있어도 먹히지만 렌더링 규칙은
 * 뒤에 있어야 이긴다는 게 실측 결과라, 형식을 마지막 블록으로 뺐습니다.
 * 캐시를 쓰지 않는 공급자라면 그냥 이어붙이면 됩니다.
 */
export function systemPrompt(card: PersonaCard, name: string): PromptBlock[] {
  return [
    { text: SHARED_RULES, cacheable: true },
    { text: characterBlock(card, name), cacheable: true },
    { text: strategyBlock(card), cacheable: true },
  ];
}
