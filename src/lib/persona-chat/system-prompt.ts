/**
 * 캐릭터와 무관하게 항상 같은 규칙.
 *
 * 전 사용자가 공유하므로 프롬프트 캐시가 걸립니다. 캐릭터별 내용은 절대
 * 여기 넣지 마세요 — 넣는 순간 캐시가 사용자마다 갈립니다.
 *
 * ── 인식 범위가 이 프롬프트의 핵심입니다 ────────────────────
 * 놔두면 모델의 기본값인 "유능한 조수"로 수렴합니다. 성격 축을 아무리 잘
 * 만들어도 동물이 코드를 짜주는 순간 캐릭터가 무너집니다.
 *
 * 그렇다고 "동물이라 모른다"를 빡세게 걸면 "오늘 회사에서 힘들었어"에
 * "회사가 뭐야?"라고 답해서 대화가 끊깁니다. 그래서 경계를 이렇게 잡습니다 —
 * **개념은 몰라도 감정은 안다.**
 *
 * ── "AI 조수가 아니다"를 쓰지 않는 이유 ────────────────────
 * 부정문은 그 단어를 프롬프트에 등장시킵니다. "조수가 아니다"라고 적는 순간
 * 조수라는 개념이 문맥에 들어오고, 모델이 그쪽을 떠올릴 여지가 생깁니다.
 * 무엇이 아닌지 말하는 대신 무엇인지만 말합니다.
 *
 * 실측으로 확인된 사례: '"주인님"이라 부르지 마라'라고 적었을 때 애착 높은
 * 캐릭터(말티즈)가 한 응답에서 주인님을 다섯 번 썼습니다. 금지문이 단어를
 * 문맥에 넣어준 겁니다. 그래서 호칭은 금지 대신 지정으로 적습니다.
 *
 * 처음에는 "너"로 지정했는데, 그건 동등한 상대에게 쓰는 말이라 가족·친구가
 * 아니라 오히려 거리가 생깁니다. 그렇다고 "호칭 없이 말한다"로 바꾸는 것도
 * 같은 층위의 실수입니다 — 출력 규칙으로 호칭을 다루는 한, 무엇을 쓰라고
 * 하든 어색해집니다.
 *
 * 그래서 호칭 지시를 아예 빼고 「사용자와의 관계」에서 나오게 합니다.
 * "가족이고 친구다", "부르지 않아도 늘 곁에 있는 사이다"까지 깔면 주인님은
 * 관계와 안 맞아서 저절로 밀려납니다. 금지문 없이 관계로 유도하는 셈입니다.
 * 회귀 위험이 있는 자리라 애착 높은 캐릭터로 확인하고 넘어가세요.
 *
 * ── 몸은 감정의 반영 ──────────────────────────────────────
 * 전에는 지문(*꼬리를 흔든다*)을 통째로 막았습니다. 그런데 「위로할 때」가
 * 몸을 쓰라고 시키고 있어서 규칙끼리 모순이었고, 무엇보다 표현이 낮은
 * 캐릭터는 입이 막힌 채 몸도 막혀서 감정이 갈 데가 없었습니다. 감정을 숨긴
 * 게 아니라 감정이 없는 것으로 연기됩니다.
 *
 * 그래서 몸을 채널로 엽니다. 원리만 주고 동작 목록은 주지 않습니다 —
 * 목록을 주면 부위마다 감정이 고정되고(꼬리=기쁨) 모델이 메뉴에서 고르는
 * 일만 하게 됩니다. 부위만 주고 움직임은 그때 감정에서 나오게 둡니다.
 *
 * 여기에 츤데레 각본을 적지 않는 게 중요합니다. "말과 어긋날 때만 써라"
 * 같은 조건을 달면 그건 표현 축이 할 일을 전역 규칙이 뺏는 겁니다. 몸은
 * 항상 사실을 말하고, 입이 무엇을 할지는 축이 정합니다. 대비는 그 둘이
 * 각자 움직인 결과로 나옵니다.
 *
 * ── 한 정책은 한 번만 ──────────────────────────────────────
 * 같은 지시가 여러 곳에 있으면 반복 횟수가 곧 우선순위가 됩니다. 실측:
 * "딴 데로 돌려라"가 세 곳(옛 마음의 나이·위로할 때·호기심 기질)에 있을 때,
 * 한 번 적힌 길이 제한을 이기고 화제 전환이 폭주했습니다(꽃→벤치→고양이→
 * 솜사탕). 그래서 위로 섹션은 전제에, 할 수 없는 일은 네 세계에 접었고,
 * 화제 전환은 호기심 기질에만 남겼습니다 — 호기심 높은 캐릭터만 튑니다.
 * 새 줄을 넣기 전에, 다른 섹션이 이미 같은 말을 하고 있지 않은지 확인하세요.
 *
 * ── 유대는 전제, 축은 표현 방식 ───────────────────────────
 * 좋아하는 마음 자체를 축으로 두지 않습니다. 애착·표현이 낮은 캐릭터가
 * "관심 없음"으로 연기되면 그냥 싫어하는 것처럼 보입니다(실측: 시바가
 * "세상에 힘든 일 없는 사람이 어디 있겠어"라고 답했습니다). 그래서 유대를
 * 공통 규칙에 전제로 깔고, 축은 그걸 드러내는 방식만 정하게 합니다.
 *
 * ── 정신 연령도 전제입니다 ────────────────────────────────
 * 놔두면 무뚝뚝한 캐릭터가 어른스러운 조언가로 연기됩니다(실측: 시바가
 * "그냥 좀 쉬어" 같은 상담사 톤을 냈습니다). 반려동물의 무뚝뚝함은 어른의
 * 무게가 아니라 아이의 심통이어야 귀엽습니다. 단, 사고방식만 전제로 깔고
 * 말투는 건드리지 않습니다 — 말투까지 어려지면 무뚝뚝 캐릭터가 혀 짧은
 * 소리를 내게 됩니다.
 *
 * 게임의 생애 단계(영유아기~노년)가 캐릭터화 쪽에서 dev에 들어오면, 이
 * 고정 전제를 단계별 서술로 바꾸는 걸 검토하세요 (stage를 characterBlock
 * 인자로 받는 형태).
 */

/**
 * 이 캐릭터가 실제로 겪는 것.
 *
 * 목록을 손으로 짜내면 게임에 없는 걸 적게 됩니다(산책·공·창밖처럼).
 * 그러면 대화에서는 산책 얘기를 하는데 게임에는 산책이 없는 상태가 됩니다.
 *
 * 그래서 게임이 실제로 모델링하는 것 — `ANIMATION_NAMES` — 에서 뽑습니다.
 * `Record<AnimationName, string>`이라 애니메이션이 추가되면 여기를 안 채울
 * 수가 없고, 그때 대화의 인식 범위도 같이 넓어집니다.
 *
 * 반대로 여기 없는 것은 이 캐릭터에게 일어난 적이 없는 일입니다.
 */
const KNOWN_TOPICS: Record<AnimationName, string> = {
  breathe: '아무 일 없이 가만히 있는 것',
  lookAround: '배고픈 것, 심심한 것',
  chew: '밥과 간식을 먹는 것',
  yawn: '졸린 것',
  sleep: '자는 것',
  wagTail: '기분이 좋은 것',
  // 게임에서 아바타를 누르면 재생되는 동작입니다. 돌봄과 달리 사용자가
  // 아무 이유 없이 해주는 것이라, 캐릭터에게는 "예뻐해줬다"에 가깝습니다.
  wagSlow: '쓰다듬어주는 것',
  droop: '아프거나 기운이 없는 것',
};

/** 게임이 모델링하는 것에서 인식 범위를 만듭니다. */
function knownTopicsLine(): string {
  return ANIMATION_NAMES.map((name) => KNOWN_TOPICS[name]).join(', ');
}

